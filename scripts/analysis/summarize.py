"""Analysis of the study: tables, figures and SUMMARY.md.

Reads ``<results>/level4/scores/<model>__<task>__s<seed>[__ckpt<pct>]/`` (written by ``scripts/eval_task.py``)
and ``<results>/level4/bench/bench__<model>__<task>__s<seed>.csv.gz`` (``scripts/zeroshot_bench.py``) and writes
to ``<results>/level4/analysis/``:

* ``curves.csv``        own-task score by model, task, seed, checkpoint, form and factor, with a 95% bootstrap
                        interval over items, macro-F1 (multiple choice) and the indicators of degenerate
                        outputs (generation: mean length, share ended, repeated bigrams);
* ``curves_seeds.csv``  mean, standard deviation and range of the own-task score over seeds;
* ``cross.csv``         score of each adapter on the other tasks and its change from the base model, with a
                        paired bootstrap interval;
* ``bench.csv``         accuracy on the general benchmarks by factor and its change from the base model;
* ``frontier.csv``      per adapter, form and factor of the reduced grid: own-task gain over the base model
                        and general cost (mean relative change over the other tasks, and over the benchmarks);
* ``kl.csv``            mean KL per token to the base model and mean negative log-likelihood per token of the
                        reference answers;
* ``equal_divergence.csv``  for each weight-space factor, the logit-space factor with the same KL (linear
                        interpolation on the grid) and the paired difference in own-task score there;
* ``attenuation.csv``   share of the own-task gain kept below factor 1;
* ``amplification.csv`` change of the own-task score from factor 1 at every factor above 1, with a paired
                        bootstrap interval, and the best factor of each form;
* ``truncated.csv``     own-task score of the adapters saved at 10%, 20% and 40% of the training steps across
                        factors, against the fully trained adapter at factor 1;
* ``fig_task_curves__<model>.pdf``, ``fig_task_frontier__<model>.pdf``, ``fig_task_truncated.pdf``;
* ``SUMMARY.md``        the main numbers in sentences.

Answers regenerated with a larger token budget (``<score file>__ext.csv``, written by
``scripts/extend_cut_outputs.py``) replace the rows they correspond to.

Every analysis that lacks its inputs is skipped with a message, so the script can run after any stage.

Usage: python scripts/analysis/summarize.py [--results DIR]
"""
import argparse
import glob
import os
import re
import sys

import numpy as np
import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
sys.path.insert(0, ROOT)
from dynalora import tasks as T  # noqa: E402
from dynalora.paths import add_results_arg, check_root  # noqa: E402

B = 2000
NAME = re.compile(r'^(?P<model>.+?)__(?P<task>[a-z0-9]+)__s(?P<seed>\d+)(?:__ckpt(?P<ckpt>\d+))?$')
TASK_LABEL = {'pubmedqa': 'PubMedQA (accuracy)', 'yelp5': 'Yelp stars (accuracy)',
              'gsm8k': 'GSM8K (exact match)', 'samsum': 'SAMSum (ROUGE-L)'}
FORMS = {'logit': ('#2a78d6', '-', 'o', 'Logit space'), 'weight': ('#eb6834', '--', 's', 'Weight space')}


def ci(x, rng):
    x = np.asarray(x, float)
    if len(x) == 0:
        return np.nan, np.nan, np.nan
    m = x[rng.integers(0, len(x), (B, len(x)))].mean(1)
    return float(x.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def _with_ext(path):
    """A score file with the rows regenerated by ``scripts/extend_cut_outputs.py`` (``<name>__ext.csv``) in place
    of the rows they replace (same factor and item; the latest budget wins)."""
    dt = {'gold': str, 'pred': str, 'item': str}
    df = pd.read_csv(path, dtype=dt)
    ext = path.replace('.csv', '__ext.csv')
    if not os.path.exists(ext):
        return df
    e = pd.read_csv(ext, dtype=dt).sort_values('budget').drop_duplicates(['factor', 'item'], keep='last')
    e['form'] = df['form'].iloc[0]
    keys = set(zip(e.factor, e.item))
    keep = df[[k not in keys for k in zip(df.factor, df.item)]]
    return pd.concat([keep, e.drop(columns=['budget'])], ignore_index=True)


def load(scores):
    """{(model, task, seed, ckpt): {'own': df, 'cross': df, 'kl': df}} with ckpt = 100 for the final adapter."""
    out = {}
    for d in sorted(glob.glob(os.path.join(scores, '*'))):
        m = NAME.match(os.path.basename(d))
        if not m or not os.path.isdir(d):
            continue
        key = (m['model'], m['task'], int(m['seed']), int(m['ckpt'] or 100))
        rec = {}
        for kind, pat in (('own', 'own__*.csv'), ('cross', 'cross_*__*.csv'), ('kl', 'kl__*.csv')):
            fs = [f for f in glob.glob(os.path.join(d, pat)) if not f.endswith('__ext.csv')]
            if fs:
                rec[kind] = pd.concat([_with_ext(f) for f in fs], ignore_index=True)
        if rec:
            out[key] = rec
    return out


def _wide(df):
    """items x factors matrix of the score of one form."""
    return df.pivot_table(index='item', columns='factor', values='score', aggfunc='first')


def curves(data, rng):
    rows = []
    for (model, task, seed, ckpt), rec in data.items():
        if 'own' not in rec:
            continue
        for (form, lam), g in rec['own'].groupby(['form', 'factor']):
            m, lo, hi = ci(g.score, rng)
            r = dict(model=model, task=task, seed=seed, ckpt=ckpt, form=form, factor=lam, n=len(g), score=m,
                     ci_lo=lo, ci_hi=hi)
            if T.spec(task)['kind'] == 'choice':
                r['macro_f1'] = T.macro_f1(list(g.gold), list(g.pred), T.spec(task)['options'])
            else:
                r.update(n_tokens=g.n_tokens.mean(), ended=g.ended.astype(float).mean(), rep2=g.rep2.mean())
            rows.append(r)
    return pd.DataFrame(rows)


def cross(data, rng):
    rows = []
    for (model, task, seed, ckpt), rec in data.items():
        if 'cross' not in rec or ckpt != 100:
            continue
        for (etask, form), g in rec['cross'].groupby(['task', 'form']):
            w = _wide(g)
            if 0.0 not in w:
                continue
            for lam in w.columns:
                d = (w[lam] - w[0.0]).dropna()
                m, lo, hi = ci(d, rng)
                rows.append(dict(model=model, task=task, seed=seed, eval_task=etask, form=form, factor=lam,
                                 score=w[lam].mean(), base=w[0.0].mean(), delta=m, delta_lo=lo, delta_hi=hi,
                                 rel_change=100 * (w[lam].mean() / w[0.0].mean() - 1) if w[0.0].mean() else np.nan))
    return pd.DataFrame(rows)


def bench(bench_dir):
    rows = []
    for f in sorted(glob.glob(os.path.join(bench_dir, 'bench__*.csv.gz'))):
        df = pd.read_csv(f)
        m = NAME.match(f'{df.model.iloc[0]}__{df.config.iloc[0]}')
        if not m:
            continue
        acc = df.groupby(['method', 'lambda', 'task'])['acc'].mean().reset_index()
        base = acc[(acc.method == 'logit') & (acc['lambda'] == 0)].set_index('task')['acc']
        for (meth, lam), g in acc.groupby(['method', 'lambda']):
            g = g.set_index('task')['acc']
            rows.append(dict(model=m['model'], task=m['task'], seed=int(m['seed']), form=meth, factor=lam,
                             acc=100 * g.mean(), base=100 * base.mean(),
                             rel_change=100 * float((g / base.reindex(g.index) - 1).mean())))
    return pd.DataFrame(rows)


def frontier(cv, cr, be):
    rows = []
    if cv.empty or cr.empty:
        return pd.DataFrame(rows)
    full = cv[cv.ckpt == 100]
    for (model, task, seed, form), g in cr.groupby(['model', 'task', 'seed', 'form']):
        own = full[(full.model == model) & (full.task == task) & (full.seed == seed) & (full.form == form)]
        own = own.set_index('factor')['score']
        if 0.0 not in own:
            continue
        for lam, h in g.groupby('factor'):
            if lam not in own:
                continue
            r = dict(model=model, task=task, seed=seed, form=form, factor=lam, own=own[lam], own_gain=own[lam] - own[0.0],
                     cross_rel_change=h.rel_change.mean(), n_cross=len(h))
            if not be.empty:
                b = be[(be.model == model) & (be.task == task) & (be.seed == seed) & (be.form == form) & (be.factor == lam)]
                if len(b):
                    r['bench_rel_change'] = float(b.rel_change.iloc[0])
            rows.append(r)
    return pd.DataFrame(rows)


def kl_table(data):
    rows = []
    for (model, task, seed, ckpt), rec in data.items():
        if 'kl' not in rec:
            continue
        for (form, lam), g in rec['kl'].groupby(['form', 'factor']):
            rows.append(dict(model=model, task=task, seed=seed, ckpt=ckpt, form=form, factor=lam, items=len(g),
                             kl_per_token=g.kl_sum.sum() / g.n_tok.sum(), nll_per_token=g.nll.sum() / g.n_tok.sum()))
    return pd.DataFrame(rows)


def equal_divergence(data, kl, rng):
    """Weight-space point against the logit-space point of the same KL to the base model."""
    rows = []
    for (model, task, seed, ckpt), rec in data.items():
        if ckpt != 100 or 'own' not in rec or kl.empty:
            continue
        k = kl[(kl.model == model) & (kl.task == task) & (kl.seed == seed) & (kl.ckpt == 100)]
        kw = k[k.form == 'weight'].set_index('factor')['kl_per_token']
        kg = k[k.form == 'logit'].sort_values('factor')
        own = rec['own']
        wl, ww = _wide(own[own.form == 'logit']), _wide(own[own.form == 'weight'])
        if kg.empty or kw.empty or wl.empty or ww.empty:
            continue
        gl, gk = kg.factor.values, kg.kl_per_token.values
        for lam_w in ww.columns:
            if lam_w in (0.0, 1.0) or lam_w not in kw:
                continue
            target = kw[lam_w]
            seg = (gl < 1) if lam_w < 1 else (gl >= 1)          # match on the same side of the trained strength
            seg = seg | (gl == 1)
            x, y = gl[seg], gk[seg]
            if not (np.all(np.diff(y) > 0) and y.min() <= target <= y.max()):
                rows.append(dict(model=model, task=task, seed=seed, factor_weight=lam_w, kl=target, factor_logit=np.nan,
                                 note='KL outside the logit grid or not monotone'))
                continue
            lam_l = float(np.interp(target, y, x))
            hi = int(np.searchsorted(x, lam_l)); hi = min(max(hi, 1), len(x) - 1)
            a, b = x[hi - 1], x[hi]
            t = 0.0 if b == a else (lam_l - a) / (b - a)
            items = ww.index.intersection(wl.index)
            sl = (1 - t) * wl.loc[items, a] + t * wl.loc[items, b]
            d = (ww.loc[items, lam_w] - sl).dropna()
            m, lo, hi_ = ci(d, rng)
            rows.append(dict(model=model, task=task, seed=seed, factor_weight=lam_w, kl=target, factor_logit=lam_l,
                             score_weight=ww.loc[items, lam_w].mean(), score_logit=sl.mean(), weight_minus_logit=m,
                             diff_lo=lo, diff_hi=hi_, note=''))
    return pd.DataFrame(rows)


def attenuation(cv):
    rows = []
    full = cv[cv.ckpt == 100] if not cv.empty else cv
    for (model, task, seed, form), g in full.groupby(['model', 'task', 'seed', 'form']) if not full.empty else []:
        s = g.set_index('factor')['score']
        if 0.0 not in s or 1.0 not in s or s[1.0] == s[0.0]:
            continue
        for lam in s.index:
            if 0 < lam < 1:
                rows.append(dict(model=model, task=task, seed=seed, form=form, factor=lam, score=s[lam], base=s[0.0],
                                 adapter=s[1.0], gain_kept=100 * (s[lam] - s[0.0]) / (s[1.0] - s[0.0])))
    return pd.DataFrame(rows)


def amplification(data, rng):
    rows = []
    for (model, task, seed, ckpt), rec in data.items():
        if 'own' not in rec:
            continue
        for form, g in rec['own'].groupby('form'):
            w = _wide(g)
            if 1.0 not in w:
                continue
            means = w.mean()
            best = float(means.idxmax())
            for lam in w.columns:
                if lam <= 1:
                    continue
                d = (w[lam] - w[1.0]).dropna()
                m, lo, hi = ci(d, rng)
                r = dict(model=model, task=task, seed=seed, ckpt=ckpt, form=form, factor=lam, score=means[lam],
                         at_one=means[1.0], delta=m, delta_lo=lo, delta_hi=hi, best_factor=best, best_score=means[best])
                if 'ended' in g:
                    h = g[g.factor == lam]
                    r.update(ended=h.ended.astype(float).mean(), n_tokens=h.n_tokens.mean(), rep2=h.rep2.mean())
                rows.append(r)
    return pd.DataFrame(rows)


def truncated(cv):
    rows = []
    if cv.empty or (cv.ckpt < 100).sum() == 0:
        return pd.DataFrame(rows)
    for (model, task, seed), g in cv.groupby(['model', 'task', 'seed']):
        full = g[(g.ckpt == 100) & (g.factor == 1.0)]
        if full.empty or (g.ckpt < 100).sum() == 0:
            continue
        ref = float(full.score.iloc[0])
        for _, r in g.iterrows():
            rows.append(dict(model=model, task=task, seed=seed, ckpt=r.ckpt, form=r.form, factor=r.factor, score=r.score,
                             ci_lo=r.ci_lo, ci_hi=r.ci_hi, full_at_one=ref, minus_full=r.score - ref))
    return pd.DataFrame(rows)


def seeds(cv):
    full = cv[cv.ckpt == 100] if not cv.empty else cv
    if full.empty:
        return full
    g = full.groupby(['model', 'task', 'form', 'factor'])['score']
    return g.agg(n_seeds='count', mean='mean', sd='std', min='min', max='max').reset_index()


# ---- figures -----------------------------------------------------------------------------------------
def _plt():
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.family': 'sans-serif', 'font.size': 8, 'axes.titlesize': 8, 'axes.labelsize': 8,
                         'xtick.labelsize': 8, 'ytick.labelsize': 8, 'legend.fontsize': 8, 'axes.linewidth': 0.6,
                         'pdf.fonttype': 42, 'ps.fonttype': 42})
    return plt


def fig_curves(cv, out):
    plt = _plt()
    full = cv[cv.ckpt == 100]
    for model, g in full.groupby('model'):
        tasks = [t for t in T.TASKS if t in set(g.task)]
        fig, axes = plt.subplots(1, len(tasks), figsize=(1.9 * len(tasks) + 0.6, 2.5), squeeze=False)
        for ax, task in zip(axes[0], tasks):
            h = g[g.task == task]
            seed0 = h.seed.min()
            for form, (color, ls, mk, label) in FORMS.items():
                s = h[(h.form == form) & (h.seed == seed0)].sort_values('factor')
                if s.empty:
                    continue
                ax.plot(s.factor, 100 * s.score, color=color, ls=ls, marker=mk, ms=3, lw=1.1, label=label)
                ax.fill_between(s.factor, 100 * s.ci_lo, 100 * s.ci_hi, color=color, alpha=0.15, lw=0)
            ax.axvline(1, color='#999', lw=0.6, ls=':')
            ax.set_title(TASK_LABEL.get(task, task)); ax.set_xlabel('Scaling factor')
        axes[0][0].set_ylabel('Own-task score (%)'); axes[0][0].legend(frameon=False)
        fig.tight_layout(); fig.savefig(os.path.join(out, f'fig_task_curves__{model}.pdf')); plt.close(fig)


def fig_frontier(fr, out):
    plt = _plt()
    for model, g in fr.groupby('model'):
        tasks = [t for t in T.TASKS if t in set(g.task)]
        fig, axes = plt.subplots(1, len(tasks), figsize=(1.9 * len(tasks) + 0.6, 2.5), squeeze=False)
        for ax, task in zip(axes[0], tasks):
            h = g[(g.task == task) & (g.seed == g.seed.min())]
            for form, (color, ls, mk, label) in FORMS.items():
                s = h[h.form == form].sort_values('factor')
                ax.plot(s.cross_rel_change, 100 * s.own, color=color, ls=ls, marker=mk, ms=3, lw=1.1, label=label)
                for _, r in s.iterrows():
                    ax.annotate(f'{r.factor:g}', (r.cross_rel_change, 100 * r.own), fontsize=6, xytext=(2, 2),
                                textcoords='offset points')
            ax.set_title(TASK_LABEL.get(task, task)); ax.set_xlabel('Change on the other tasks (%)')
        axes[0][0].set_ylabel('Own-task score (%)'); axes[0][0].legend(frameon=False)
        fig.tight_layout(); fig.savefig(os.path.join(out, f'fig_task_frontier__{model}.pdf')); plt.close(fig)


def fig_truncated(tr, out):
    plt = _plt()
    tr = tr[tr.form == 'logit']
    tasks = [t for t in T.TASKS if t in set(tr.task)]
    if not tasks:
        return
    fig, axes = plt.subplots(1, len(tasks), figsize=(1.9 * len(tasks) + 0.6, 2.5), squeeze=False)
    colors = {10: '#c2308f', 20: '#e8641b', 40: '#c9a000', 100: '#1f5fbf'}
    for ax, task in zip(axes[0], tasks):
        h = tr[tr.task == task]
        for ckpt, s in h.groupby('ckpt'):
            s = s.sort_values('factor')
            ax.plot(s.factor, 100 * s.score, marker='o', ms=3, lw=1.1, color=colors.get(int(ckpt), '#555'),
                    label=f'{int(ckpt)}% of the steps')
        ax.axhline(100 * h.full_at_one.iloc[0], color='#999', lw=0.6, ls=':')
        ax.set_title(TASK_LABEL.get(task, task)); ax.set_xlabel('Logit-space factor')
    axes[0][0].set_ylabel('Own-task score (%)'); axes[0][0].legend(frameon=False)
    fig.tight_layout(); fig.savefig(os.path.join(out, 'fig_task_truncated.pdf')); plt.close(fig)


# ---- summary -----------------------------------------------------------------------------------------
def summary(cv, fr, eq, at, am, tr, sd):
    L = ['# Task adapters against human labels: summary', '']
    full = cv[cv.ckpt == 100] if not cv.empty else cv
    for model, g in full.groupby('model') if not full.empty else []:
        L += [f'## {model}', '']
        for task in [t for t in T.TASKS if t in set(g.task)]:
            h = g[(g.task == task) & (g.seed == g[g.task == task].seed.min())]
            lo = h[h.form == 'logit'].set_index('factor')
            we = h[h.form == 'weight'].set_index('factor')
            if 0.0 not in lo.index or 1.0 not in lo.index:
                continue
            L.append(f'**{TASK_LABEL.get(task, task)}.** Base model {100 * lo.score[0.0]:.1f}, adapter at factor 1 '
                     f'{100 * lo.score[1.0]:.1f} (95% interval {100 * lo.ci_lo[1.0]:.1f} to {100 * lo.ci_hi[1.0]:.1f}).')
            for name, s in (('Logit space', lo), ('Weight space', we)):
                if s.empty:
                    continue
                b = s.score.idxmax()
                L.append(f'- {name}: best factor {b:g} ({100 * s.score[b]:.1f}); '
                         + ', '.join(f'{f:g}: {100 * v:.1f}' for f, v in s.score.items()) + '.')
            a = at[(at.model == model) & (at.task == task) & (at.seed == h.seed.min())] if not at.empty else at
            if len(a):
                L.append('- Share of the gain kept below factor 1: '
                         + '; '.join(f'{r.form} {r.factor:g}: {r.gain_kept:.0f}%' for r in a.itertuples()) + '.')
            f = fr[(fr.model == model) & (fr.task == task) & (fr.seed == h.seed.min())] if not fr.empty else fr
            if len(f):
                L.append('- Change on the other tasks (mean relative change, %): '
                         + '; '.join(f'{r.form} {r.factor:g}: {r.cross_rel_change:+.1f}' for r in f.itertuples()) + '.')
            e = eq[(eq.model == model) & (eq.task == task) & (eq.seed == h.seed.min())] if not eq.empty else eq
            e = e[e.factor_logit.notna()] if len(e) else e
            if len(e):
                L.append('- Equal divergence, weight minus logit (points): '
                         + '; '.join(f'weight {r.factor_weight:g} vs logit {r.factor_logit:.2f}: '
                                     f'{100 * r.weight_minus_logit:+.1f} [{100 * r.diff_lo:+.1f}, {100 * r.diff_hi:+.1f}]'
                                     for r in e.itertuples()) + '.')
            L.append('')
    if not sd.empty and sd.n_seeds.max() > 1:
        L += ['## Seeds', '']
        for r in sd[(sd.factor == 1.0) & (sd.form == 'logit')].itertuples():
            L.append(f'- {r.model}, {r.task}, factor 1: mean {100 * r.mean:.1f}, standard deviation {100 * r.sd:.1f} '
                     f'over {r.n_seeds} seeds.')
        L.append('')
    if not tr.empty:
        L += ['## Truncated training', '']
        for (model, task, ckpt), g in tr[tr.ckpt < 100].groupby(['model', 'task', 'ckpt']):
            for form, h in g.groupby('form'):
                b = h.loc[h.score.idxmax()]
                one = h[h.factor == 1.0]
                L.append(f'- {model}, {task}, {int(ckpt)}% of the steps, {form}: factor 1 gives '
                         f'{100 * float(one.score.iloc[0]) if len(one) else float("nan"):.1f}, best factor {b.factor:g} gives '
                         f'{100 * b.score:.1f}; fully trained adapter at factor 1: {100 * b.full_at_one:.1f}.')
        L.append('')
    return '\n'.join(L) + '\n'


def main():
    ap = add_results_arg(argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter))
    ap.add_argument('--level', default='level4', help='subdirectory of the results root (default: level4)')
    ap.add_argument('--seed', type=int, default=0, help='seed of the bootstrap')
    a = ap.parse_args()
    root = os.path.join(check_root(a.results), a.level)
    out = os.path.join(root, 'analysis'); os.makedirs(out, exist_ok=True)
    rng = np.random.default_rng(a.seed)
    data = load(os.path.join(root, 'scores'))
    if not data:
        raise SystemExit(f'no scores under {root}/scores')
    cv = curves(data, rng); cr = cross(data, rng); be = bench(os.path.join(root, 'bench'))
    fr = frontier(cv, cr, be); kl = kl_table(data); eq = equal_divergence(data, kl, rng)
    at = attenuation(cv); am = amplification(data, rng); tr = truncated(cv); sd = seeds(cv)
    for name, df in (('curves', cv), ('curves_seeds', sd), ('cross', cr), ('bench', be), ('frontier', fr), ('kl', kl),
                     ('equal_divergence', eq), ('attenuation', at), ('amplification', am), ('truncated', tr)):
        if df is None or df.empty:
            print(f'{name}: no input yet, skipped'); continue
        df.to_csv(os.path.join(out, f'{name}.csv'), index=False)
        print(f'{name}.csv: {len(df)} rows')
    if not cv.empty:
        fig_curves(cv, out)
    if not fr.empty:
        fig_frontier(fr, out)
    if not tr.empty:
        fig_truncated(tr, out)
    with open(os.path.join(out, 'SUMMARY.md'), 'w') as f:
        f.write(summary(cv, fr, eq, at, am, tr, sd))
    print(open(os.path.join(out, 'SUMMARY.md')).read())


if __name__ == '__main__':
    main()
